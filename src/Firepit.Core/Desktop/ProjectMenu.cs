using System.Text;

namespace Firepit.Core.Desktop;

/// <summary>Where the freedesktop menu files go; the XDG defaults unless a test says otherwise.</summary>
public sealed record ProjectMenuLocations(string Applications, string Directories, string MergedMenus)
{
    public static ProjectMenuLocations Default
    {
        get
        {
            var home = Environment.GetFolderPath(Environment.SpecialFolder.UserProfile);
            var data = Environment.GetEnvironmentVariable("XDG_DATA_HOME") is { Length: > 0 } d ? d : Path.Combine(home, ".local", "share");
            var config = Environment.GetEnvironmentVariable("XDG_CONFIG_HOME") is { Length: > 0 } c ? c : Path.Combine(home, ".config");
            return new ProjectMenuLocations(
                Applications: Path.Combine(data, "applications", ProjectMenu.FolderName),
                Directories: Path.Combine(data, "desktop-directories"),
                MergedMenus: Path.Combine(config, "menus", "applications-merged"));
        }
    }
}

/// <summary>
/// The start menu's "Projects" submenu: one entry per project that opens it
/// in Claude (<c>firepitd open &lt;path&gt;</c>), found by KRunner as well. A
/// freedesktop menu, so any desktop that follows the menu spec shows it.
/// </summary>
/// <remarks>
/// The entries live in their own folder, <c>applications/firepit/</c>, which
/// makes their desktop ids <c>firepit-&lt;name&gt;.desktop</c> and lets a sync
/// remove what is no longer a project without touching anything else. A sync
/// writes only what changed, so an unchanged project list costs a directory
/// listing.
/// </remarks>
public static class ProjectMenu
{
    public const string FolderName = "firepit";
    public const string Category = "X-Firepit-Project";
    public const string DirectoryFileName = "firepit-projects.directory";
    public const string MenuFileName = "firepit-projects.menu";
    public const string MenuName = "Projects";

    /// <summary>The central project's folder name, shown under a readable name.</summary>
    private const string CentralFolder = ".firepit";

    public static string DisplayName(string projectName, string projectPath) =>
        string.Equals(Path.GetFileName(Path.TrimEndingDirectorySeparator(projectPath)), CentralFolder, PlatformText.Paths)
            ? "Firepit central"
            : projectName;

    /// <summary>A file name from a project name: lowercase letters, digits and dashes.</summary>
    public static string FileStem(string displayName)
    {
        var sb = new StringBuilder();
        foreach (var ch in displayName.ToLowerInvariant())
        {
            sb.Append(char.IsAsciiLetterOrDigit(ch) ? ch : '-');
        }
        var stem = sb.ToString().Trim('-');
        while (stem.Contains("--", StringComparison.Ordinal)) stem = stem.Replace("--", "-", StringComparison.Ordinal);
        return stem.Length == 0 ? "project" : stem;
    }

    public static string Entry(string displayName, string projectPath, string launcherPath) =>
        $"""
        [Desktop Entry]
        Type=Application
        Version=1.5
        Name={Value(displayName)}
        GenericName=Claude Code project
        Comment={Value($"Open {displayName} in Claude: its session, or a new one")}
        Icon=claude-desktop
        Exec={Value($"{Arg(launcherPath)} open {Arg(projectPath)}").Replace("%", "%%", StringComparison.Ordinal)}
        Categories={Category};
        Keywords=claude;project;firepit;
        StartupNotify=false
        X-Firepit-Project={Value(projectPath)}

        """;

    public static string DirectoryFile =>
        $"""
        [Desktop Entry]
        Type=Directory
        Version=1.5
        Name={MenuName}
        Comment=Your projects, each opening in Claude
        Icon=folder-development

        """;

    public static string MenuFile =>
        $"""
        <!DOCTYPE Menu PUBLIC "-//freedesktop//DTD Menu 1.0//EN"
            "http://www.freedesktop.org/standards/menu-spec/menu-1.0.dtd">
        <!-- Generated by Firepit (firepitd); rewritten on every project change. -->
        <Menu>
            <Name>Applications</Name>
            <Menu>
                <Name>{MenuName}</Name>
                <Directory>{DirectoryFileName}</Directory>
                <Include>
                    <Category>{Category}</Category>
                </Include>
            </Menu>
        </Menu>

        """;

    /// <summary>
    /// Brings the menu in line with <paramref name="projects"/>: writes
    /// entries that are new or changed, removes the ones whose project is
    /// gone. Returns whether anything on disk changed, so the caller knows
    /// whether the desktop's menu cache needs a rebuild.
    /// </summary>
    public static bool Sync(IEnumerable<(string Name, string Path)> projects, string launcherPath, ProjectMenuLocations at)
    {
        Directory.CreateDirectory(at.Applications);
        Directory.CreateDirectory(at.Directories);
        Directory.CreateDirectory(at.MergedMenus);

        var changed = WriteIfDifferent(Path.Combine(at.Directories, DirectoryFileName), DirectoryFile);
        changed |= WriteIfDifferent(Path.Combine(at.MergedMenus, MenuFileName), MenuFile);

        var wanted = new Dictionary<string, string>(StringComparer.Ordinal);
        foreach (var (name, path) in projects.OrderBy(p => p.Path, StringComparer.Ordinal))
        {
            var display = DisplayName(name, path);
            var stem = FileStem(display);
            var file = stem;
            for (var n = 2; wanted.ContainsKey(file + ".desktop"); n++) file = $"{stem}-{n}";
            wanted[file + ".desktop"] = Entry(display, path, launcherPath);
        }

        foreach (var (file, content) in wanted)
        {
            changed |= WriteIfDifferent(Path.Combine(at.Applications, file), content);
        }

        foreach (var existing in Directory.EnumerateFiles(at.Applications, "*.desktop"))
        {
            if (wanted.ContainsKey(Path.GetFileName(existing))) continue;
            File.Delete(existing);
            changed = true;
        }
        return changed;
    }

    private static bool WriteIfDifferent(string path, string content)
    {
        if (File.Exists(path) && File.ReadAllText(path) == content) return false;
        var temp = path + ".tmp";
        File.WriteAllText(temp, content);
        File.Move(temp, path, overwrite: true);
        return true;
    }

    /// <summary>
    /// One argument of an Exec line: in double quotes, with the four
    /// characters the spec reserves inside quotes escaped.
    /// </summary>
    private static string Arg(string value)
    {
        var sb = new StringBuilder("\"");
        foreach (var ch in value)
        {
            if (ch is '"' or '`' or '$' or '\\') sb.Append('\\');
            sb.Append(ch);
        }
        return sb.Append('"').ToString();
    }

    /// <summary>
    /// A desktop-entry string value on one line, backslashes doubled: values
    /// are unescaped before an Exec line is split into arguments. In Exec a
    /// "%" also has to be doubled, or it reads as a field code.
    /// </summary>
    private static string Value(string value) =>
        value.Replace("\\", "\\\\", StringComparison.Ordinal)
             .Replace("\r", " ", StringComparison.Ordinal)
             .Replace("\n", " ", StringComparison.Ordinal);
}
