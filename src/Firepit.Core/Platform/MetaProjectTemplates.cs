using Firepit.Core.Blueprints;
using Firepit.Core.ProjectConfig;

namespace Firepit.Core.Platform;

/// <summary>
/// What firepitd seeds into a missing central project. The CLAUDE.md
/// sections every project carries are taken from
/// <see cref="FirepitBlueprintDefaults"/> rather than copied, so the central
/// project cannot fall out of step with them; only the knowledge and pinned
/// sections differ, because this repository holds two bases.
/// </summary>
internal static class MetaProjectTemplates
{
    /// <summary>The <c>id</c> in the central project's <c>.firepit/config.json</c>.</summary>
    public const string ProjectId = "firepit-central";

    public static string ClaudeMd(string metaProjectPath) =>
        ClaudeMdIntro + "\n" +
        FirepitBlueprintDefaults.InboxSection + "\n" +
        KnowledgeSection + "\n" +
        PinnedSection + "\n" +
        FirepitFragments.ResolveSection(
            FirepitBlueprintDefaults.FragmentsSection, metaProjectPath, metaProjectPath);

    public static string ConfigJson => ProjectConfigScaffold.BuildScaffold(ProjectId);

    private const string ClaudeMdIntro = """
        # Firepit central project

        The repository one level above the projects. It holds what belongs to the
        whole tree rather than to one repository in it: the global knowledge base,
        the shared `CLAUDE.md` fragments, the blueprints and what this repository
        keeps about other projects. It is a project too, with its own `.firepit/`.

        ## Layout

        | Path | What it is |
        |---|---|
        | `knowledge/` | The global knowledge base, read by every project |
        | `knowledge-pinned.md` | The global base's pinned documents, regenerated by Firepit |
        | `projects/claude.md` | Shared policy, imported into every project's `CLAUDE.md` |
        | `projects/claude-github-public.md`, `projects/claude-github-private.md` | Policy that depends on a repository's GitHub visibility |
        | `projects/<name>/` | What this repository keeps about another project, such as the knowledge of a public repository |
        | `blueprints/<name>/` | What a project carries: `CLAUDE.md` sections, seeded files, ignore rules |
        | `.firepit/` | This project's own config, inbox and knowledge |

        ## Working here

        - An edit to `projects/claude*.md` reaches every project with its next
          session. Keep the fragments to policy; the tools describe themselves.
        - Blueprints are edited as files. `firepit_blueprint_check` without a
          project shows what each project lacks, `firepit_blueprint_apply` brings
          one in line, and `firepit_integrity_check` reports drift in the knowledge
          index and the fragment imports.
        - Other projects' code is changed in their own sessions. Send them a
          message with `firepit_send_to`; it waits in their inbox until a session
          handles it.

        """;

    private const string KnowledgeSection = """
        ## Firepit knowledge

        Before researching something that may already be known, query the
        knowledge base with the `firepit_knowledge_search` MCP tool (scope `both`
        covers this project plus the global base). Save durable findings with
        `firepit_knowledge_add`, written in English, per the indexing convention.

        This repository holds two bases:

        | Scope | Documents | For |
        |---|---|---|
        | `global` | `knowledge/` | Anything worth knowing across projects |
        | this project | `.firepit/knowledge/` | Notes about running the central project itself |

        Save to `global` unless the finding is about administering this
        repository. Both are committed; the `knowledge.db` beside each is derived
        and ignored.

        """;

    private const string PinnedSection = """
        ## Firepit pinned knowledge

        @knowledge-pinned.md
        @.firepit/knowledge-pinned.md

        The imports above auto-load the knowledge docs marked `pin: true` in their
        frontmatter: the first from the global base, the second from this
        project's own. Firepit regenerates both from the pinned docs; don't edit
        them directly. Pin/unpin via the pinned flag on `firepit_knowledge_add` /
        `firepit_knowledge_update`, and keep the pinned set small.

        """;

    public const string ReadmeMd = """
        # Firepit central project

        The repository at the top of the projects root, where Firepit keeps what
        belongs to all projects: the global knowledge base, the shared `CLAUDE.md`
        fragments, the blueprints and notes about other projects. It is a project
        as well. A Claude Code session opened here has the `firepit_*` tools like
        any other, and `CLAUDE.md` is its brief.

        firepitd seeded this project because it was missing, and it never
        overwrites a file in it. Commit it like any other repository. It collects
        notes about every project, including the ones a public repository keeps
        out of itself, so give it a private remote.

        | Path | What it is | Commit it? |
        |---|---|---|
        | `knowledge/*.md` | The global knowledge base | yes |
        | `knowledge-pinned.md` | Its pinned documents, regenerated by Firepit | yes |
        | `knowledge.db*` | Its search index, derived from the documents | no |
        | `projects/claude*.md` | The shared `CLAUDE.md` fragments | yes |
        | `projects/<name>/` | Notes and knowledge about another project | yes |
        | `blueprints/` | The blueprints | yes |
        | `.firepit/` | This project's own config, knowledge and inbox | as in any project |

        Firepit itself: https://github.com/SACRVM/firepit-ai

        """;

    // What Claude Code reads for project-scope servers. It asks once before a
    // session in this folder may start the server.
    public const string McpJson = """
        {
          "mcpServers": {
            "firepit": {
              "type": "stdio",
              "command": "firepit-mcp"
            }
          }
        }

        """;

    public const string GlobalKnowledgeReadme = """
        # Global knowledge

        The knowledge base every project reads: findings, conventions and project
        cards worth knowing beyond one repository.

        - Search it with `firepit_knowledge_search` (scope `global`, or `both`
          from any project) and add to it with `firepit_knowledge_add`; correct or
          retire stale docs with `firepit_knowledge_update` /
          `firepit_knowledge_delete`.
        - One markdown file per topic, written in English (the search index
          embeds English best). The files are committed.
        - `../knowledge.db` is the derived search index: ignored, and rebuilt from
          the markdown at any time.
        - Docs whose frontmatter says `pin: true` are compiled into
          `../knowledge-pinned.md`, which the central project's `CLAUDE.md`
          imports.

        """;

    // Every line of ProjectScaffolding.GitignoreEntries is here as well, so
    // the central project passes the blueprint check like any other.
    public const string GitIgnore = """
        # Search indexes: derived from the markdown beside them, rebuilt on demand
        /knowledge.db*
        projects/*/knowledge.db*

        # Firepit + Claude Code — shared config versioned, runtime/personal local
        .firepit/inbox/
        .firepit/runs/
        .firepit/knowledge.db*
        !.firepit/config.json
        .claude/settings.local.json
        .claude/*.lock
        .claude/agent-memory/

        """;
}
